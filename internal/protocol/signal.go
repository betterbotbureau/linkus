package protocol

import (
	"encoding/json"
	"strings"
	"time"
)

// Signaling messages. All signaling is JSON with a "v":1
// field. The service relays SDP as an opaque string with length checks
// only; it never parses it.
const (
	// SignalVersion is the protocol version carried in every signaling
	// message.
	SignalVersion = 1
	// MaxSignalMessageBytes caps signaling messages on the visitor socket
	// and on the presence socket once it also carries signaling.
	MaxSignalMessageBytes = 16 * 1024
	// MaxSDPBytes caps the SDP carried inside one signaling message. An
	// SDP with a handful of candidates is 1 to 4 KB; this leaves room for
	// pathological-but-honest router setups while keeping the whole JSON
	// message under MaxSignalMessageBytes.
	MaxSDPBytes = 15 * 1024
	// VisitIDLength is the length of a visit ID: 16 lowercase hex digits
	// (8 random bytes), generated by the service.
	VisitIDLength = 16
	// MaxVisitorMessages is the most messages a visitor socket may send.
	MaxVisitorMessages = 4
	// VisitorSocketLifetime is how long a visitor socket may exist before
	// the service closes it, answered or not.
	VisitorSocketLifetime = 60 * time.Second
	// DefaultMaxVisits is how many visitor connections one node accepts at
	// a time unless its owner sets another number (MinMaxVisits to
	// MaxMaxVisits); offers beyond that are answered with "busy".
	DefaultMaxVisits = 32
	MinMaxVisits     = 1
	MaxMaxVisits     = 200
	// MaxAnswerSigBytes caps the base64 answer signature. An Ed25519
	// signature is 64 bytes, 88 in base64; the cap leaves margin without
	// letting the field carry anything else.
	MaxAnswerSigBytes = 120
	// ProbeNonceLength is the length of a probe nonce: 16 lowercase hex
	// digits, chosen by the node.
	ProbeNonceLength = 16
	// ProbeMagic prefixes every mapping-verification probe datagram; the
	// node's nonce follows it.
	ProbeMagic = "linkus-probe-v1 "
	// ProbePackets is how many probe datagrams the service sends.
	ProbePackets = 3
	// ProbePacketSpacing is the gap between probe datagrams.
	ProbePacketSpacing = 300 * time.Millisecond
)

// Signal message types.
//
// Visitor socket (GET /v1/visit?id=...):
//
//	service → visitor  "offline" (with last_seen), "answer" (with sdp), "busy"
//	visitor → service  "offer" (with sdp)
//
// Presence socket, after authentication:
//
//	service → node  "visit-offer"  (visit, sdp)
//	node → service  "visit-answer" (visit, sdp), "visit-busy" (visit)
//
// Presence socket, verification additions:
//
//	node → service  "probe" (addr, nonce): ask the service to send UDP
//	                probe packets at the node's claimed mapped address
//	service → node  "probe-sent" after the packets go out
//
// Presence socket, protected folders:
//
//	service → node  "auth-check" (visit = attempt ID, email): may this
//	                address sign in? Asked before a code is mailed.
//	node → service  "auth-allow" or "auth-deny" (visit = attempt ID)
const (
	SignalOffer       = "offer"
	SignalAnswer      = "answer"
	SignalOffline     = "offline"
	SignalBusy        = "busy"
	SignalVisitOffer  = "visit-offer"
	SignalVisitAnswer = "visit-answer"
	SignalVisitBusy   = "visit-busy"
	SignalProbe       = "probe"
	SignalProbeSent   = "probe-sent"
	SignalAuthCheck   = "auth-check"
	SignalAuthAllow   = "auth-allow"
	SignalAuthDeny    = "auth-deny"
	// SignalSuspended tells a visitor the name is frozen for abuse
	//; the node cannot serve while it stands.
	SignalSuspended = "suspended"
)

// SignalMessage is one signaling message on either socket. Unused fields
// are omitted on the wire.
type SignalMessage struct {
	V        int    `json:"v"`
	Type     string `json:"type"`
	Visit    string `json:"visit,omitempty"`     // visit ID, presence socket only
	SDP      string `json:"sdp,omitempty"`       // opaque to the service
	Sig      string `json:"sig,omitempty"`       // base64 Ed25519 over AnswerSigningBytes
	LastSeen string `json:"last_seen,omitempty"` // RFC 3339, "offline" only
	Addr     string `json:"addr,omitempty"`      // "ip:port", "probe" only
	Nonce    string `json:"nonce,omitempty"`     // 16 lowercase hex, "probe" only
	// From is the visitor's IP address as the service saw it, on
	// "visit_offer" only, so the node can cap visits per address before
	// answering. Older nodes ignore it; nodes treat it as a hint.
	From string `json:"from,omitempty"`
	// Email is the address a visitor wants to sign in with, on
	// "auth-check" only.
	Email string `json:"email,omitempty"`
}

// Encode marshals a signaling message for the wire.
func (m SignalMessage) Encode() ([]byte, error) { return json.Marshal(m) }

// DecodeSignalMessage parses a signaling message, rejecting oversized input.
func DecodeSignalMessage(data []byte) (SignalMessage, error) {
	var m SignalMessage
	if len(data) > MaxSignalMessageBytes {
		return m, ErrMessageTooLarge
	}
	err := json.Unmarshal(data, &m)
	return m, err
}

// ValidVisitID reports whether s has the exact visit ID form: 16 lowercase
// hex digits.
func ValidVisitID(s string) bool { return lowerHex(s, VisitIDLength) }

// ValidProbeNonce reports whether s has the exact probe nonce form: 16
// lowercase hex digits.
func ValidProbeNonce(s string) bool { return lowerHex(s, ProbeNonceLength) }

func lowerHex(s string, n int) bool {
	if len(s) != n {
		return false
	}
	for i := 0; i < len(s); i++ {
		c := s[i]
		if (c < '0' || c > '9') && (c < 'a' || c > 'f') {
			return false
		}
	}
	return true
}

// NodeIDLength is the length of a node ID; a node's address is its ID
// under the names domain (58310427.mdoc.us).
const NodeIDLength = 8

// NodeIDAlphabet is every character a node ID may hold: digits and
// lowercase letters without i, l and o, which read like 1 and 0 — as on
// number plates. 33 characters. IDs are issued as digits today; letters
// let the space grow from 90 million to about 1.4 trillion without longer
// addresses, so everything already accepts them.
const NodeIDAlphabet = "0123456789abcdefghjkmnpqrstuvwxyz"

// ValidNodeID reports whether s is a well-formed node ID.
func ValidNodeID(s string) bool {
	if len(s) != NodeIDLength {
		return false
	}
	for i := 0; i < len(s); i++ {
		if strings.IndexByte(NodeIDAlphabet, s[i]) < 0 {
			return false
		}
	}
	return true
}
